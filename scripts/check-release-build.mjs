/**
 * Release build hygiene — validates dist/ before it can act as a release artifact.
 * Run after npm run build: node scripts/check-release-build.mjs
 * Exits non-zero on any deterministic production-hygiene failure.
 */

import fs from "fs";
import path from "path";
import { fileURLToPath } from "url";
import { SITE_ORIGIN } from "./landing-pages-data.mjs";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const DIST_DIR = path.join(__dirname, "..", "dist");

const TEXT_EXTENSIONS = new Set([
  ".html",
  ".js",
  ".mjs",
  ".css",
  ".xml",
  ".txt",
  ".json",
  ".svg",
  ".webmanifest",
  ".map",
]);

// Protocol-prefixed on purpose: bare hostname comparisons (e.g. the Turnstile
// local-preview detection in ContactPage.tsx) are legitimate production code;
// only URL-shaped references indicate an accidental local/staging endpoint.
const FORBIDDEN_HOST_PATTERNS = [
  { label: "localhost URL", pattern: /https?:\/\/localhost/i },
  { label: "loopback IP URL (127.0.0.1)", pattern: /https?:\/\/127\.0\.0\.1/ },
  { label: "unspecified IP URL (0.0.0.0)", pattern: /https?:\/\/0\.0\.0\.0/ },
  { label: "workers.dev preview URL", pattern: /https?:\/\/[^\s"'`]+\.workers\.dev/i },
  { label: "pages.dev preview URL", pattern: /https?:\/\/[^\s"'`]+\.pages\.dev/i },
  { label: "staging URL", pattern: /https?:\/\/[^\s"'`]*staging[.-]/i },
];

// Generated by @cloudflare/vite-plugin; its wrangler dev defaults (dev.ip etc.)
// are boilerplate, not shipped content, so it is excluded from content scans.
const CONTENT_SCAN_EXCLUSIONS = new Set(["wrangler.json"]);

const DEV_ARTIFACT_PATTERNS = [
  { label: "Vite dev client reference", pattern: /@vite\/client/ },
  { label: "Vite dev HMR marker", pattern: /__vite_ping/ },
  { label: "sourcemap reference", pattern: /sourceMappingURL/ },
];

const failures = [];
const warnings = [];

function fail(message) {
  failures.push(message);
}

function warn(message) {
  warnings.push(message);
}

function walk(dir) {
  const entries = [];
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const fullPath = path.join(dir, entry.name);
    if (entry.isDirectory()) {
      entries.push(...walk(fullPath));
    } else if (entry.isFile()) {
      entries.push(fullPath);
    }
  }
  return entries;
}

function relative(filePath) {
  return path.relative(DIST_DIR, filePath).split(path.sep).join("/");
}

if (!fs.existsSync(DIST_DIR)) {
  fail("dist/ does not exist — run `npm run build` first.");
} else {
  const allFiles = walk(DIST_DIR);

  if (allFiles.length === 0) {
    fail("dist/ is empty — the production build produced no output.");
  }

  if (!fs.existsSync(path.join(DIST_DIR, "index.html"))) {
    fail("dist/index.html is missing.");
  }

  const sitemapPath = path.join(DIST_DIR, "sitemap.xml");
  if (!fs.existsSync(sitemapPath)) {
    fail("dist/sitemap.xml is missing.");
  } else {
    const sitemap = fs.readFileSync(sitemapPath, "utf8");
    if (!sitemap.includes("<urlset")) {
      fail("dist/sitemap.xml is not a valid sitemap (missing <urlset>).");
    }
    const locs = [...sitemap.matchAll(/<loc>\s*([^<]+?)\s*<\/loc>/g)].map((m) => m[1]);
    if (locs.length === 0) {
      fail("dist/sitemap.xml contains no <loc> entries.");
    }
    for (const loc of locs) {
      if (!loc.startsWith(`${SITE_ORIGIN}/`) && loc !== `${SITE_ORIGIN}/`) {
        fail(`dist/sitemap.xml contains a non-production URL: ${loc}`);
      }
    }
  }

  const robotsPath = path.join(DIST_DIR, "robots.txt");
  if (!fs.existsSync(robotsPath)) {
    fail("dist/robots.txt is missing.");
  } else {
    const robots = fs.readFileSync(robotsPath, "utf8");
    if (!robots.includes(`Sitemap: ${SITE_ORIGIN}/sitemap.xml`)) {
      fail("dist/robots.txt does not reference the production sitemap URL.");
    }
  }

  const sourcemaps = allFiles.filter((f) => f.endsWith(".map"));
  for (const file of sourcemaps) {
    fail(`Source map must not ship in the production build: ${relative(file)}`);
  }

  if (!fs.existsSync(path.join(DIST_DIR, "og-image.png"))) {
    warn("dist/og-image.png is missing — OG/Twitter cards will have no image.");
  }

  for (const file of allFiles) {
    const ext = path.extname(file).toLowerCase();
    if (!TEXT_EXTENSIONS.has(ext) || ext === ".map") {
      continue;
    }
    if (CONTENT_SCAN_EXCLUSIONS.has(path.basename(file))) {
      continue;
    }
    const stat = fs.statSync(file);
    if (stat.size > 5 * 1024 * 1024) {
      warn(`Skipping oversized file during content scan: ${relative(file)}`);
      continue;
    }
    const content = fs.readFileSync(file, "utf8");
    const rel = relative(file);

    for (const { label, pattern } of FORBIDDEN_HOST_PATTERNS) {
      if (pattern.test(content)) {
        fail(`${label} found in ${rel}`);
      }
    }
    for (const { label, pattern } of DEV_ARTIFACT_PATTERNS) {
      if (pattern.test(content)) {
        fail(`${label} found in ${rel}`);
      }
    }
    if (ext === ".html" && /noindex/i.test(content)) {
      fail(`Accidental noindex directive found in ${rel}`);
    }
  }

  const measurementId = process.env.VITE_GA_MEASUREMENT_ID?.trim();
  if (measurementId) {
    const bundleContainsId = allFiles
      .filter((f) => f.endsWith(".js"))
      .some((f) => fs.readFileSync(f, "utf8").includes(measurementId));
    if (!bundleContainsId) {
      fail(
        "VITE_GA_MEASUREMENT_ID is set but was not found in any built JS bundle — the build does not represent production analytics configuration."
      );
    }
  } else {
    warn(
      "VITE_GA_MEASUREMENT_ID not provided to this check — skipped analytics parity verification."
    );
  }
}

for (const message of warnings) {
  console.warn(`WARNING: ${message}`);
}
for (const message of failures) {
  console.error(`FAIL: ${message}`);
}

if (failures.length > 0) {
  console.error(`\nRelease build hygiene: ${failures.length} blocking problem(s) found.`);
  process.exit(1);
}

console.log("Release build hygiene: all checks passed.");
